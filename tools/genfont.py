#!/usr/bin/env python3
"""Rasterizes the OFL fonts in third_party/fonts into lib/gfx/fonts.cpp.

Usage: tools/genfont.py  (requires Pillow). The output is committed so the
regular build does not need Python.
"""
import os
from PIL import Image, ImageDraw, ImageFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FONTS = [
    # (C++ name, file, pixel size)
    ("font_mono", "SourceCodePro-Regular.ttf", 13),
    ("font_sans", "Lato-Regular.ttf", 14),
    ("font_title", "Lato-Regular.ttf", 22),
]


def render(path, size):
    font = ImageFont.truetype(path, size)
    ascent, descent = font.getmetrics()
    glyphs, alpha = [], []
    for code in range(32, 127):
        ch = chr(code)
        img = Image.new("L", (96, 96), 0)
        ImageDraw.Draw(img).text((24, 64), ch, font=font, fill=255, anchor="ls")
        box = img.getbbox()
        adv = int(round(font.getlength(ch)))
        if not box:
            glyphs.append((adv, 0, 0, 0, 0, len(alpha)))
            continue
        x0, y0, x1, y1 = box
        crop = img.crop(box)
        glyphs.append((adv, x0 - 24, y0 - 64, x1 - x0, y1 - y0, len(alpha)))
        alpha.extend(crop.tobytes())
    return ascent, descent, glyphs, alpha


def main():
    out = ["// Generated by tools/genfont.py; do not edit. Fonts: see third_party/fonts.",
           '#include "fishos/gfx.h"', "", "namespace gfx {"]
    for name, fname, size in FONTS:
        ascent, descent, glyphs, alpha = render(os.path.join(ROOT, "third_party/fonts", fname), size)
        out.append(f"static const uint8_t {name}_alpha[{len(alpha)}] = {{")
        for i in range(0, len(alpha), 24):
            out.append("    " + ",".join(str(b) for b in alpha[i:i + 24]) + ",")
        out.append("};")
        out.append(f"const Font {name} = {{{ascent + descent}, {ascent}, {{")
        for g in glyphs:
            out.append("    {%d, %d, %d, %d, %d, %d}," % g)
        out.append(f"}}, {name}_alpha}};")
        out.append("")
    out.append("}")
    with open(os.path.join(ROOT, "lib/gfx/fonts.cpp"), "w") as f:
        f.write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
